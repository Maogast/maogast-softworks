function adjustPrice(oldPrice: number): number {
  const increase = oldPrice * 0.3;
  const cappedIncrease = Math.min(increase, 1000);
  const newPrice = oldPrice + cappedIncrease;
  // round to nearest 5
  return Math.round(newPrice / 5) * 5;
}

